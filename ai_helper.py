"""Groq integration with honest demo-mode fallbacks."""
import os
from dotenv import load_dotenv

load_dotenv()


def live_ai_available():
    return bool(os.getenv("GROQ_API_KEY", "").strip() and os.getenv("GROQ_MODEL", "").strip())


def _chat(system_prompt, user_prompt):
    if not live_ai_available():
        return None
    try:
        from groq import Groq
        client = Groq(api_key=os.environ["GROQ_API_KEY"], timeout=30.0)
        response = client.chat.completions.create(
            model=os.environ["GROQ_MODEL"],
            messages=[{"role": "system", "content": system_prompt}, {"role": "user", "content": user_prompt}],
            temperature=0.3,
        )
        return response.choices[0].message.content.strip()
    
    except Exception as exc:
        print("GROQ ERROR TYPE:", type(exc).__name__)
        print("GROQ ERROR DETAILS:", str(exc))
        raise RuntimeError(
            "Live AI request failed. Check your Groq settings and connection, then try again."
        ) from exc



def analyze(metrics):
    prompt = "Explain these calculated city statistics in beginner-friendly language. Use only supplied facts and numbers. Mention the highest traffic and AQI locations, notable patterns, and data limitations. Do not invent causes or claim emergency status.\n\n" + str(metrics)
    answer = _chat("You are a careful educational smart-city data analyst. Distinguish measurements from interpretations.", prompt)
    if answer:
        return {"mode": "live", "label": "Live AI analysis", "text": answer}
    return {"mode": "demo", "label": "Demo explanation (not generated by AI)", "text": f"The highest average traffic is at {metrics['highest_traffic_location']}, while the highest average AQI is at {metrics['highest_aqi_location']}. There are {metrics['high_traffic_readings']} readings above the configured traffic threshold and {metrics['high_aqi_readings']} readings above the configured AQI threshold. These are educational sample/data indicators and should be checked against reliable local measurements."}


def recommendations(metrics):
    prompt = "Give 3 to 5 practical, cautious, informational recommendations based only on these metrics. Do not present them as official traffic-control or public-health instructions.\n\n" + str(metrics)
    answer = _chat("You provide cautious educational data recommendations. Never invent facts.", prompt)
    if answer:
        return {"mode": "live", "label": "Live AI recommendations", "items": [line.strip(" -*0123456789.\t") for line in answer.splitlines() if line.strip()]}
    return {"mode": "demo", "label": "Demo recommendations (not generated by AI)", "items": [f"Review traffic patterns at {metrics['highest_traffic_location']} using additional time-of-day data.", f"Consider follow-up monitoring at {metrics['highest_aqi_location']}, which has the highest average AQI in this dataset.", "Collect more weeks of readings before making operational decisions.", "Check sensor calibration, missing values, and measurement provenance before publishing findings."]}


def ask(question, metrics):
    prompt = f"Question: {question}\n\nCalculated dataset context: {metrics}\n\nAnswer only from the supplied context. If unavailable, say the dataset does not provide the answer. Do not invent numeric values."
    answer = _chat("You are a precise assistant answering questions about city traffic and AQI data. Explain simply and distinguish facts from inference.", prompt)
    if answer:
        return {"mode": "live", "label": "Live AI answer", "answer": answer}
    q = question.lower()
    if "highest traffic" in q:
        answer = f"{metrics['highest_traffic_location']} has the highest average traffic in this dataset."
    elif "worst" in q or "highest average aqi" in q or "highest aqi" in q:
        answer = f"{metrics['highest_aqi_location']} has the highest average AQI in this dataset."
    elif "growth" in q:
        changes = metrics["traffic"]["percent_change_by_location"]
        idx = max(range(len(changes)), key=lambda i: changes[i] if changes[i] is not None else float("-inf"))
        answer = f"{metrics['locations'][idx]} has the highest percentage change from the first to last day ({changes[idx]}%)."
    else:
        answer = "Demo mode can answer basic questions about the highest traffic location, highest average AQI, and traffic growth. Configure GROQ_API_KEY and GROQ_MODEL for live natural-language answers."
    return {"mode": "demo", "label": "Demo answer (not generated by AI)", "answer": answer}


def explain(subject, metrics):
    prompt = f"Explain this selected analysis in beginner-friendly language: {subject}. Use only these calculated metrics: {metrics}"
    answer = _chat("You are a friendly teacher explaining numerical analytics. Do not add unsupported facts.", prompt)
    if answer:
        return {"mode": "live", "label": "Live AI explanation", "text": answer}
    return {"mode": "demo", "label": "Demo explanation (not generated by AI)", "text": f"This view is based on {metrics['total_readings']} readings across {len(metrics['locations'])} locations. The calculations summarize the values in the currently loaded dataset. Demo mode uses a predefined explanation rather than a live language model."}
